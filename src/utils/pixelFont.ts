function parse(sheet: string): Map<string, string[]> {
  const glyphs = new Map<string, string[]>();
  for (const block of sheet.trim().split(/\n\s*\n/)) {
    const [header, ...rows] = block.split('\n');
    let col = 0;
    for (const width of rows[0].split(' ').map(g => g.length)) {
      glyphs.set(header[col], rows.map(r => r.slice(col, col + width)));
      col += width + 1;
    }
  }
  return glyphs;
}

export const GLYPHS = parse(SHEET);
